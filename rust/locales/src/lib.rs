//! Localized strings for Witcher3StringEditor ported from C# .resx resources.
#![forbid(unsafe_code)]

pub const SUPPORTED_CULTURES: &[(&str, &str)] = &[
    ("en", "English"),
    ("de", "Deutsch"),
    ("fr", "Français"),
    ("hu-hu", "Magyar"),
    ("id-ID", "Bahasa Indonesia"),
    ("ja-jp", "日本語"),
    ("pl-pl", "Polski"),
    ("pt-br", "Português (Brasil)"),
    ("th-TH", "ไทย"),
    ("uk-ua", "Українська"),
    ("zh-Hans", "简体中文"),
    ("zh-Hant", "繁體中文"),
];

pub fn resolve_culture(target: &str) -> &'static str {
    let lower = target.to_ascii_lowercase();
    for &(code, _) in SUPPORTED_CULTURES {
        if code.eq_ignore_ascii_case(&lower) {
            return code;
        }
    }
    if lower.starts_with("zh-cn") || lower.starts_with("zh-sg") {
        return "zh-Hans";
    }
    if lower.starts_with("zh-tw") || lower.starts_with("zh-hk") || lower.starts_with("zh-mo") {
        return "zh-Hant";
    }
    let parent = lower.split('-').next().unwrap_or("");
    for &(code, _) in SUPPORTED_CULTURES {
        let code_parent = code.split('-').next().unwrap_or("");
        if code_parent.eq_ignore_ascii_case(parent) {
            return code;
        }
    }
    "en"
}

pub fn get(culture: &str, key: &str) -> &'static str {
    let cult = resolve_culture(culture);
    lookup(cult, key).unwrap_or_else(|| {
        lookup("en", key).unwrap_or("")
    })
}

